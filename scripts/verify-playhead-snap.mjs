/* global document */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import console from 'node:console';
import process from 'node:process';
import { verification } from './browser-test-utils.mjs';
import { captureEvidenceScreenshot } from './browser-screenshot.mjs';
const suite = verification('playhead-snap', 3102);
const { evidence, baseURL, ff } = suite;
let page;
const checks = [], errors = [];
const check = (name, value = true) => {
  assert(value, name); checks.push(name); console.log('PASS', name);
  fs.writeFileSync(`${evidence}/browser-results.json`, JSON.stringify({ checks, errors }, null, 2));
};
(async () => {
  ff(['-y', '-f', 'lavfi', '-i', 'testsrc2=size=160x120:rate=30:duration=4', '-c:v', 'libx264', `${evidence}/source.mp4`]);
  await suite.start();
  const browser = await suite.launch();
  page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(baseURL);
  await page.locator('.asset-library input[type=file]').setInputFiles(`${evidence}/source.mp4`);
  await page.locator('.asset-card').waitFor();
  await page.waitForFunction(() => !document.querySelector('.asset-library input').disabled);
  await page.locator('.asset-card').dragTo(page.locator('.timeline-track-row').last(), { targetPosition: { x: 48, y: 30 } });
  const clip = page.locator('.timeline-clip');
  await clip.waitFor();
  const undo = page.getByTitle('Undo (Ctrl+Z)', { exact: true });
  const redo = page.getByTitle('Redo (Shift+Ctrl+Z)', { exact: true });
  const left = () => clip.evaluate(el => parseFloat(el.style.left) - 48);
  const seek = async (sec, pps = 80) => {
    const scroll = await page.locator('.timeline-scroll').boundingBox();
    const ruler = await page.locator('.timeline-ruler').boundingBox();
    await page.mouse.click(scroll.x + 48 + sec * pps, ruler.y + 8);
  };
  const begin = async (delta) => {
    const box = await clip.boundingBox();
    await page.mouse.move(box.x + 24, box.y + 20);
    await page.mouse.down();
    await page.mouse.move(box.x + 24 + delta, box.y + 20, { steps: 5 });
    await page.waitForFunction(() => document.querySelector('.timeline-clip--dragging'));
  };
  const expectLeft = async (px) => {
    await page.waitForFunction(expected => Math.abs(parseFloat(document.querySelector('.timeline-clip').style.left) - 48 - expected) < 0.02, px);
  };
  await seek(2.5);
  await begin(2.5 * 80 - 6);
  await expectLeft(200);
  check('start edge snaps within 8 CSS pixels during real pointer drag');
  await page.keyboard.down('Alt');
  await expectLeft(194);
  check('stationary Alt disables snapping without pointer movement');
  await page.keyboard.up('Alt');
  await expectLeft(200);
  check('stationary Alt release restores snapping from raw position');
  await captureEvidenceScreenshot(page, `${evidence}/snapped-drag.png`);
  const preview = await left();
  await page.mouse.up();
  await expectLeft(preview);
  check('pointer release commits the rendered preview exactly');
  await undo.click(); await expectLeft(0);
  check('one Undo restores the original position');
  await redo.click(); await expectLeft(preview);
  check('Redo restores the exact snapped position');
  await undo.click();
  await seek(5.5);
  await begin(1.5 * 80 + 6);
  await expectLeft(120);
  check('end edge snaps to the playhead');
  await page.mouse.up();
  await undo.click();
  for (let i = 0; i < 4; i++) await page.locator('.timeline-toolbar-right').getByRole('button', { name: '+', exact: true }).click();
  await seek(2.5, 160);
  await begin(2.5 * 160 - 8);
  await expectLeft(400);
  check('inclusive 8 CSS pixel threshold also applies at zoom 2');
  await page.mouse.up(); await undo.click();
  await begin(2.5 * 160 - 10);
  await expectLeft(390);
  check('outside threshold remains unsnapped at zoom 2');
  await page.mouse.up(); await undo.click();
  // A movement that crosses the activation threshold and returns is a no-op.
  const box = await clip.boundingBox();
  await page.mouse.move(box.x + 24, box.y + 20); await page.mouse.down();
  await page.mouse.move(box.x + 44, box.y + 20);
  await page.mouse.move(box.x + 24, box.y + 20);
  await page.mouse.up();
  await expectLeft(0);
  check('no-op drag preserves pending Redo', await redo.isEnabled());
  for (let i = 0; i < 4; i++) await page.locator('.timeline-toolbar-right').getByRole('button', { name: '−', exact: true }).click();
  const slider = page.locator('.timeline-toolbar-right input[type=range]');
  await slider.focus();
  await begin(2.5 * 80 - 6);
  await expectLeft(200);
  await page.keyboard.press('End');
  await expectLeft(2.425 * 320);
  check('stationary zoom changes derive snapping from the original raw position');
  await page.keyboard.press('Home');
  await expectLeft(2.5 * 20);
  await page.dispatchEvent('.timeline-scroll', 'pointercancel', { pointerId: 1 });
  await page.mouse.up();
  await expectLeft(0);
  check('pointer cancellation discards the preview and preserves Redo', await redo.isEnabled());
  await slider.focus(); await page.keyboard.press('Home');
  for (let i = 0; i < 3; i++) await page.keyboard.press('ArrowRight');
  await seek(0);
  await page.getByTitle('再生 / 一時停止 (Space)', { exact: true }).click();
  await begin(120);
  await page.waitForFunction(() => {
    const start = parseFloat(document.querySelector('.timeline-clip').style.left) - 48;
    const head = parseFloat(document.querySelector('.timeline-ruler .timeline-playhead').style.left) - 48;
    return head > 113 && head < 128 && Math.abs(head - start) < 0.02;
  });
  check('playback continues and live snapping follows the moving playhead with a stationary pointer');
  await page.evaluate(() => document.addEventListener('pointerup', () => {
    document.body.dataset.dropPreview = document.querySelector('.timeline-clip').style.left;
  }, { once: true, capture: true }));
  await page.mouse.up();
  const playbackDrop = await page.locator('body').getAttribute('data-drop-preview');
  assert.equal(await clip.evaluate(el => el.style.left), playbackDrop);
  await page.waitForFunction(() => parseFloat(document.querySelector('.timeline-ruler .timeline-playhead').style.left) > parseFloat(document.body.dataset.dropPreview) + 20);
  assert.equal(await clip.evaluate(el => el.style.left), playbackDrop);
  check('playback pointerup commits the last rendered preview and subsequent playback cannot move it');
  await page.getByTitle('再生 / 一時停止 (Space)', { exact: true }).click();
  await undo.click(); await expectLeft(0);
  await seek(0);
  await page.getByTitle('再生 / 一時停止 (Space)', { exact: true }).click();
  await begin(120);
  await page.waitForFunction(() => {
    const head = parseFloat(document.querySelector('.timeline-ruler .timeline-playhead').style.left) - 48;
    return head > 135;
  });
  await expectLeft(120);
  check('live snapping disengages when playback leaves the threshold');
  await page.mouse.up();
  await page.getByTitle('再生 / 一時停止 (Space)', { exact: true }).click();
  await undo.click(); await expectLeft(0);
  await seek(2.5);
  for (let i = 0; i < 4; i++) await page.locator('.timeline-toolbar-right').getByRole('button', { name: '+', exact: true }).click();
  await begin(2.5 * 160 - 6); await expectLeft(400);
  // The stable capture owner must survive moving a clip into another row.
  const target = await page.locator('.timeline-track-row').first().boundingBox();
  const dragged = await clip.boundingBox();
  await page.mouse.move(dragged.x + 24 - 6, target.y + 20);
  await page.waitForFunction(() => !!document.querySelector('.timeline-track-row .timeline-clip--dragging'));
  const committedLeft = await left();
  await page.mouse.up(); await expectLeft(committedLeft);
  check('cross-track pointer capture survives preview remount', await page.locator('.timeline-track-row').first().locator('.timeline-clip').count() === 1);
  await page.getByRole('button', { name: '新しい保存版を保存', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('.busy-banner'));
  const saved = await page.request.get(`${baseURL}/api/projects`);
  const project = (await saved.json()).projects.at(-1);
  const documentResponse = await page.request.get(`${baseURL}/api/projects/${project.id}`);
  const savedDocument = await documentResponse.json();
  fs.writeFileSync(`${evidence}/saved-project.json`, JSON.stringify(savedDocument, null, 2));
  assert(Math.abs(savedDocument.project.clips[0].timelineStartSec - committedLeft / 160) < 1e-9);
  check('saved document retains the displayed move time and source duration', savedDocument.project.clips[0].durationSec === 4);
  await page.getByText(/サーバーの保存版/).click();
  await page.locator('.project-revision').last().getByRole('button', { name: '読み込み', exact: true }).click();
  await expectLeft(committedLeft);
  check('loading a saved version preserves the exact committed move');
  const payloadPromise = page.waitForRequest(request => request.url().endsWith('/api/jobs/export-composition') && request.method() === 'POST');
  const downloadPromise = page.waitForEvent('download', { timeout: 120000 });
  await page.getByTitle('全体書き出し (Ctrl+E)').click();
  const payload = (await payloadPromise).postDataJSON();
  fs.writeFileSync(`${evidence}/export-payload.json`, JSON.stringify(payload, null, 2));
  await (await downloadPromise).saveAs(`${evidence}/snapped-export.mp4`);
  ff(['-xerror', '-i', `${evidence}/snapped-export.mp4`, '-f', 'null', '-']);
  assert.deepEqual(payload.clips[0].parts, savedDocument.project.clips[0].parts);
  assert.equal(payload.clips[0].timelineStartSec, savedDocument.project.clips[0].timelineStartSec);
  check('real export retains saved move time and source parts and fully decodes');
  await captureEvidenceScreenshot(page, `${evidence}/committed.png`);
  check('no uncaught runtime errors', errors.length === 0);
})().catch(async error => {
  console.error(error); fs.writeFileSync(`${evidence}/failure.txt`, String(error.stack ?? error));
  if (page && !page.isClosed()) await page.screenshot({ path: `${evidence}/failure.png` }).catch(() => { /* Preserve original failure. */ });
  process.exitCode = 1;
}).finally(() => suite.cleanup());
